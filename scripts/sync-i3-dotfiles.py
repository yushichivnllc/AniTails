#!/usr/bin/env python3
"""
AniTails — i3 desktop manifest generator & verifier.

The i3 stack is AniTails-written (GPL-3.0-or-later) and checked into the
repository, so there is nothing to "sync" from an upstream source tree. This
script regenerates the SHA-256 manifest and UPSTREAM.json, and can verify an
already-generated manifest against the on-disk tree.

Usage:
  python3 scripts/sync-i3-dotfiles.py           # regenerate MANIFEST.sha256 + UPSTREAM.json
  python3 scripts/sync-i3-dotfiles.py --check   # verify existing manifest, exit 1 on mismatch
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
VENDOR_DIR = REPO_ROOT / "archiso/airootfs/usr/share/anitails/i3"
MANIFEST = VENDOR_DIR / "MANIFEST.sha256"
UPSTREAM = VENDOR_DIR / "UPSTREAM.json"
SOURCE_ROOT = "Configs"


def git_head() -> str:
    try:
        res = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True,
        )
        return res.stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return "unknown"


def tracked_files() -> list[Path]:
    """All files under the i3 vendor tree (git index preferred)."""
    rel_root = "archiso/airootfs/usr/share/anitails/i3"
    try:
        res = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "ls-files", "--cached", "--others",
             "--exclude-standard", "--", rel_root],
            capture_output=True, text=True, check=True,
        )
        rel_paths = [ln.strip() for ln in res.stdout.splitlines() if ln.strip()]
    except (subprocess.CalledProcessError, OSError):
        rel_paths = []
    if not rel_paths:
        # Fallback for environments without git metadata: walk the tree.
        rel_paths = [
            p.relative_to(REPO_ROOT).as_posix()
            for p in VENDOR_DIR.rglob("*")
            if p.is_file()
        ]
    paths = []
    for rel in rel_paths:
        if rel in ("MANIFEST.sha256", "UPSTREAM.json"):
            continue
        path = REPO_ROOT / rel
        if path.is_file():
            paths.append(path)
    return sorted(paths)


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def generate() -> int:
    files = tracked_files()
    if not files:
        print("error: no tracked i3 files found (commit them first)", file=sys.stderr)
        return 1

    lines = []
    for path in files:
        rel = path.relative_to(VENDOR_DIR).as_posix()
        if rel in ("MANIFEST.sha256", "UPSTREAM.json"):
            continue
        lines.append(f"{sha256_of(path)}  {rel}\n")

    MANIFEST.write_text(
        "# AniTails i3 desktop stack — generated by scripts/sync-i3-dotfiles.py\n"
        "# Format: <sha256>  <relative-path>\n"
        + "".join(lines),
        encoding="utf-8",
    )

    upstream = {
        "project": "AniTails i3 desktop stack",
        "repository": "anitails:local",
        "upstream_project": "anitails:self",
        "license": "GPL-3.0-or-later",
        "version": "1.0.0",
        "commit": git_head(),
        "file_count": len(lines),
        "note": "Self-written i3-gaps design system; no upstream vendoring. "
                "See docs/I3WM_INTEGRATION.md.",
    }
    UPSTREAM.write_text(json.dumps(upstream, indent=2) + "\n", encoding="utf-8")

    print(f"generated {MANIFEST} ({len(lines)} files) and {UPSTREAM}")
    return 0


def check() -> int:
    if not MANIFEST.is_file():
        print("error: manifest missing", file=sys.stderr)
        return 1
    entries: dict[str, str] = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        digest, sep, rel = line.partition("  ")
        if not sep:
            print(f"error: malformed manifest line: {line!r}", file=sys.stderr)
            return 1
        entries[rel] = digest
    problems: list[str] = []
    for rel, expected in entries.items():
        path = VENDOR_DIR / rel
        if not path.is_file():
            problems.append(f"missing {rel}")
            continue
        if sha256_of(path) != expected:
            problems.append(f"hash mismatch {rel}")
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 1
    print(f"PASS: {len(entries)} file(s) verified against MANIFEST.sha256")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate/verify the i3 desktop manifest")
    parser.add_argument("--check", action="store_true", help="verify, do not regenerate")
    args = parser.parse_args()
    if args.check:
        return check()
    return generate()


if __name__ == "__main__":
    raise SystemExit(main())
