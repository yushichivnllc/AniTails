#!/usr/bin/env python3
"""
AniTails — AniDE/HyDE dotfiles vendoring tool.

Copies the audited subset of the pinned AniDE (HyDE) repository into
`archiso/airootfs/usr/share/anitails/hyde/` and writes:

  * `UPSTREAM.json`       — provenance record (repo, commit, tag, date, exclusions)
  * `MANIFEST.sha256`     — per-file SHA-256 of everything that was vendored

The ISO build must never reach the network for desktop configuration, so the
dotfiles are vendored in-tree and pinned by hash. `anitails-hyde-seed` verifies
`MANIFEST.sha256` before it writes anything into the live user's `$HOME`.

Usage:
    python3 scripts/sync-hyde-dotfiles.py --source /path/to/AniDE
    python3 scripts/sync-hyde-dotfiles.py --source /path/to/AniDE --check

`--check` re-verifies the vendored tree against `MANIFEST.sha256` without
touching the working tree (used by the test suite).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
VENDOR_DIR = REPO_ROOT / "archiso/airootfs/usr/share/anitails/hyde"
# AniTails-authored replacements/additions, kept in-tree as the source of truth
# and copied into the vendored tree so the ISO only has to trust one manifest.
OVERRIDE_SRC = REPO_ROOT / "archiso/hyde-overrides"

# Everything below is intentionally NOT vendored.
#   * dconf            — GNOME configuration backend; AniTails has no GNOME left.
#   * Code/VSCodium    — editors that are not part of the AniTails package set.
#   * .local/state     — runtime state of the upstream author, never seeded.
#   * hydectl/hyde-ipc — unaudited prebuilt ELF blobs; AniTails refuses to ship
#                        opaque third-party binaries (see docs/HYDE_INTEGRATION.md).
#                        The HyDE shell itself is plain bash/python and does not
#                        need them; only `hyde-shell version` reports them absent.
EXCLUDED_PATHS = [
    "Configs/.config/dconf",
    "Configs/.config/Code",
    "Configs/.config/Code - OSS",
    "Configs/.config/VSCodium",
    "Configs/.local/state",
    "Configs/.local/bin/hydectl",
    "Configs/.local/bin/hyde-ipc",
    "Configs/.config/zsh/completions/hydectl.zsh",
]

# Documented purpose of each AniTails override (source: archiso/hyde-overrides/).
OVERRIDES = {
    "overrides/.config/hyde/config.toml": "AniTails desktop defaults (Tor Browser, Waybar fallback, no lock)",
    "overrides/.config/hypr/hyprland.lua": "upstream hyprland.lua + `require('anitails')` hook",
    "overrides/.config/hypr/anitails.lua": "AniTails keybinds, wallpaper and bar bootstrap",
    "overrides/.config/hypr/hypridle.conf": "no lock listener (live user has a locked password)",
}

GENERATED_MARKER = "# Generated by AniTails scripts/sync-hyde-dotfiles.py — do not edit in-tree.\n"


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git(source: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(source), *args],
        capture_output=True, text=True, check=True,
    ).stdout.strip()


def iter_files(root: Path):
    for path in sorted(root.rglob("*")):
        if path.is_symlink() or path.is_file():
            yield path


def vendor(source: Path, dest: Path) -> None:
    configs = source / "Configs"
    if not configs.is_dir():
        sys.exit(f"error: {configs} not found — pass --source pointing at an AniDE checkout")

    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    exclusions = [source / p for p in EXCLUDED_PATHS]

    def excluded(path: Path) -> bool:
        return any(path == exc or exc in path.parents for exc in exclusions)

    copied = 0
    for src in iter_files(configs):
        if excluded(src) or "__pycache__" in src.parts:
            continue
        target = dest / "Configs" / src.relative_to(configs)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        copied += 1

    license_src = source / "LICENSE"
    if license_src.is_file():
        shutil.copy2(license_src, dest / "LICENSE")

    missing = [rel for rel in OVERRIDES if not (OVERRIDE_SRC / rel.removeprefix("overrides/")).is_file()]
    if missing:
        sys.exit("error: missing AniTails override(s) under archiso/hyde-overrides/: " + ", ".join(missing))
    for src in iter_files(OVERRIDE_SRC):
        target = dest / "overrides" / src.relative_to(OVERRIDE_SRC)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)

    commit = git(source, "rev-parse", "HEAD")
    upstream = {
        "project": "AniDE (HyDE fork)",
        "repository": "https://github.com/hyprdes/AniDE",
        "upstream_project": "https://github.com/HyDE-Project/HyDE",
        "license": "GPL-3.0-only",
        "commit": commit,
        "commit_date": git(source, "log", "-1", "--date=iso-strict", "--format=%ad"),
        "commit_subject": git(source, "log", "-1", "--format=%s"),
        "dotfiles_version": (source / "Scripts/dots/hyde.toml").read_text(encoding="utf-8")
        .split('version = "', 1)[-1].split('"', 1)[0]
        if (source / "Scripts/dots/hyde.toml").is_file() else "unknown",
        "vendored_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "vendored_files": copied,
        "excluded_paths": EXCLUDED_PATHS,
        "anitails_overrides": OVERRIDES,
        "notes": [
            "Only the Configs/ tree is vendored; Scripts/ (installer, deez-dots, AUR helpers) is not.",
            "Prebuilt binaries hydectl and hyde-ipc are excluded on purpose (no opaque blobs).",
            "AniTails never runs the upstream installer at runtime; anitails-hyde-seed copies files offline.",
        ],
    }
    (dest / "UPSTREAM.json").write_text(
        json.dumps(upstream, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    lines = [GENERATED_MARKER.rstrip("\n")]
    for path in iter_files(dest):
        rel = path.relative_to(dest).as_posix()
        if rel == "MANIFEST.sha256":
            continue
        lines.append(f"{sha256_of(path)}  {rel}")
    (dest / "MANIFEST.sha256").write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = sum(p.stat().st_size for p in iter_files(dest))
    print(f"vendored {copied} files ({total / 1024 / 1024:.1f} MiB) from {commit[:12]} -> {dest.relative_to(REPO_ROOT)}")


def verify(dest: Path) -> int:
    manifest = dest / "MANIFEST.sha256"
    if not manifest.is_file():
        print(f"error: {manifest} missing; run without --check first", file=sys.stderr)
        return 2
    problems = []
    listed: set[str] = set()
    for line in manifest.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        digest, _, rel = line.partition("  ")
        listed.add(rel)
        target = dest / rel
        if not target.is_file():
            problems.append(f"missing: {rel}")
            continue
        actual = sha256_of(target)
        if actual != digest:
            problems.append(f"hash mismatch: {rel} (expected {digest[:12]}, got {actual[:12]})")
    for path in iter_files(dest):
        rel = path.relative_to(dest).as_posix()
        if rel in ("MANIFEST.sha256", "UPSTREAM.json") or path.name == ".gitkeep":
            continue
        if rel not in listed:
            problems.append(f"unlisted file: {rel}")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print(f"FAIL: {len(problems)} problem(s) in vendored dotfiles", file=sys.stderr)
        return 1
    print(f"OK: {len(listed)} vendored dotfiles match MANIFEST.sha256")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, help="path to an AniDE git checkout (required unless --check)")
    parser.add_argument("--dest", type=Path, default=VENDOR_DIR)
    parser.add_argument("--check", action="store_true", help="verify an existing vendored tree")
    args = parser.parse_args()

    if args.check:
        return verify(args.dest)
    if not args.source:
        parser.error("--source is required")
    vendor(args.source.resolve(), args.dest)
    return verify(args.dest)


if __name__ == "__main__":
    raise SystemExit(main())
