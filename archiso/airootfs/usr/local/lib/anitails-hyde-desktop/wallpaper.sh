#!/usr/bin/env bash
# AniTails — deterministic wallpaper bootstrap for the HyDE Hyprland session.
#
# HyDE's `wallpaper.sh --start` expects a themed wallpaper directory
# (`$HYDE_THEME_DIR/wall.set`) that the offline installer would normally have
# downloaded. AniTails ships exactly one pinned wallpaper instead, so the
# desktop never needs the network — or a theme fetch — to look alive.
#
# Backend order: hyprpaper (official) -> awww -> swww.
set -uo pipefail
export PATH="/usr/local/bin:${PATH}"

WALL="${ANITAILS_WALLPAPER:-/usr/share/anitails/wallpapers/anitails-default.png}"
if [[ ! -f $WALL ]]; then
    printf 'wallpaper.sh: %s is missing\n' "$WALL" >&2
    exit 1
fi

config_home="${XDG_CONFIG_HOME:-$HOME/.config}"

start_hyprpaper() {
    local conf="${config_home}/hypr/hyprpaper.conf"
    if [[ ! -f $conf ]]; then
        mkdir -p "${config_home}/hypr"
        cat >"$conf" <<EOF
# Generated by AniTails (anitails-hyde-desktop/wallpaper.sh)
splash = false
preload = ${WALL}
wallpaper = ,${WALL}
EOF
    fi
    pgrep -u "$(id -u)" -x hyprpaper >/dev/null 2>&1 || hyprpaper >/dev/null 2>&1 &
    for _ in $(seq 1 50); do
        if hyprctl hyprpaper listloaded >/dev/null 2>&1; then break; fi
        sleep 0.1
    done
    hyprctl hyprpaper preload "$WALL" >/dev/null 2>&1 || true
    hyprctl hyprpaper wallpaper ",$WALL" >/dev/null 2>&1
}

start_awww() {
    if ! pgrep -u "$(id -u)" -x awww-daemon >/dev/null 2>&1; then
        awww-daemon --format xrgb >/dev/null 2>&1 &
        for _ in $(seq 1 50); do
            awww query >/dev/null 2>&1 && break
            sleep 0.1
        done
    fi
    awww img "$WALL" --transition-type grow --transition-duration 1 --transition-fps 60
}

start_swww() {
    if ! pgrep -u "$(id -u)" -x swww-daemon >/dev/null 2>&1; then
        swww-daemon >/dev/null 2>&1 &
        for _ in $(seq 1 50); do
            swww query >/dev/null 2>&1 && break
            sleep 0.1
        done
    fi
    swww img "$WALL" --transition-type grow --transition-duration 1
}

if ! command -v hyprctl >/dev/null 2>&1 || [[ -z ${HYPRLAND_INSTANCE_SIGNATURE:-} ]]; then
    # Not inside a Hyprland session (e.g. started from a test harness) — the
    # compositor will run this script again once the session is up.
    printf 'wallpaper.sh: no running Hyprland instance; skipping wallpaper\n' >&2
    exit 0
fi

if command -v hyprpaper >/dev/null 2>&1; then
    start_hyprpaper && exit 0
fi
if command -v awww >/dev/null 2>&1; then
    start_awww && exit 0
fi
if command -v swww >/dev/null 2>&1; then
    start_swww && exit 0
fi

printf 'wallpaper.sh: no wallpaper backend available (hyprpaper/awww/swww)\n' >&2
exit 1
